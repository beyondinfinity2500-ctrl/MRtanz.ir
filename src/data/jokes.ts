export function getJokeBySlug(slug: string): Joke | undefined {
  return jokes.find((j) => j.slug === slug);
}

export function getRelatedJokes(joke: Joke, count = 3): Joke[] {
  const scored = jokes
    .filter((j) => j.id !== joke.id)
    .map((j) => {
      let score = 0;
      if (j.category === joke.category) score += 3;
      const shared = j.tags.filter((t) => joke.tags.includes(t)).length;
      score += shared;
      return { joke: j, score };
    });

  scored.sort((a, b) => b.score - a.score);
  return scored.slice(0, count).map((s) => s.joke);
}

export function getJokeCategories(): string[] {
  return [...new Set(jokes.map((j) => j.category))];
}

export function getRandomJoke(): Joke {
  return jokes[Math.floor(Math.random() * jokes.length)];
}

export function getFeaturedJoke(): Joke {
  return jokes[0];
}
